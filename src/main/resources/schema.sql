CREATE TABLE IF NOT EXISTS links (
  code VARCHAR(32) PRIMARY KEY,
  destination VARCHAR(2048) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE,
  disabled BOOLEAN NOT NULL DEFAULT FALSE,
  clicks BIGINT NOT NULL DEFAULT 0,
  idempotency_key VARCHAR(128) UNIQUE
);
CREATE TABLE IF NOT EXISTS clicks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(32) NOT NULL,
  clicked_at TIMESTAMP WITH TIME ZONE NOT NULL,
  FOREIGN KEY (code) REFERENCES links(code)
);
CREATE INDEX IF NOT EXISTS idx_clicks_code_time ON clicks(code, clicked_at);
CREATE TABLE IF NOT EXISTS workflow_runs (
  id VARCHAR(40) PRIMARY KEY,
  state CLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS workflow_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id VARCHAR(40) NOT NULL,
  occurred_at VARCHAR(48) NOT NULL,
  event_type VARCHAR(60) NOT NULL,
  detail CLOB NOT NULL,
  prev_hash VARCHAR(64) NOT NULL,
  event_hash VARCHAR(64) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_workflow_events_run ON workflow_events(run_id, id);
